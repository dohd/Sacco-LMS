<?php

namespace App\Http\Controllers\LoanRepaymentSchedules;

use App\Http\Controllers\Controller;
use App\Models\LoanApplications\LoanRepaymentSchedule;
use App\Models\Memberships\Member;

class LoanRepaymentSchedulesController extends Controller
{
    public function __construct()
    {
        $this->middleware(function ($request, $next) {
            abort_unless(in_array($request->route()->getActionMethod(), ['index', 'show'], true),
                405, 'Repayment schedules are generated by loan approval and cannot be manually changed.');
            return $next($request);
        });
    }

    public function index()
    {
        $query = LoanRepaymentSchedule::latest();
        if (!$this->hasSaccoPermission('review-loan')) {
            $this->requireSaccoPermission('view-own-loan');
            $query->whereIn('member_id', Member::where('user_id', auth()->id())->select('id'));
        }
        $schedules = $query->get();
        return view('loan_repayment_schedules.index', compact('schedules'));
    }

    public function show(LoanRepaymentSchedule $loan_repayment_schedule)
    {
        $schedule = $loan_repayment_schedule;
        if (!$this->hasSaccoPermission('review-loan')) {
            $this->requireSaccoPermission('view-own-loan');
            abort_unless(Member::whereKey($schedule->member_id)->where('user_id', auth()->id())->exists(), 403);
        }
        return view('loan_repayment_schedules.view', compact('schedule'));
    }

    public function create() { abort(405); }
    public function store() { abort(405); }
    public function edit() { abort(405); }
    public function update() { abort(405); }
    public function destroy() { abort(405); }
}
