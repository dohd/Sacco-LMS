<?php

namespace App\Http\Controllers;

use Illuminate\Foundation\Auth\Access\AuthorizesRequests;
use Illuminate\Foundation\Bus\DispatchesJobs;
use Illuminate\Foundation\Validation\ValidatesRequests;
use Illuminate\Routing\Controller as BaseController;

class Controller extends BaseController
{
    use AuthorizesRequests, DispatchesJobs, ValidatesRequests;

    protected function ownsMember($memberId): bool
    {
        return auth()->check() && \App\Models\Memberships\Member::whereKey($memberId)
            ->where('user_id', auth()->id())->exists();
    }

    protected function rejectSystemFields(\Illuminate\Http\Request $request, array $fields = []): void
    {
        if ($request->isMethod('get')) {
            return;
        }
        $fields = array_merge($fields, ['created_by', 'created_at', 'updated_at', 'approved_by',
            'approved_at', 'processed_by', 'processed_at', 'confirmed_by', 'confirmed_at',
            'recorded_by', 'reversed_by', 'reversed_at', 'opened_by', 'closed_by', 'closed_date',
            'paid_by', 'paid_at', 'requested_by', 'verified_by', 'verified_at', 'submitted_by', 'submitted_at',
            'balance_before', 'balance_after', 'running_balance', 'running_units', 'reversal_of_id',
            'ledger_balance', 'available_balance', 'held_balance', 'share_balance',
            'held_amount', 'available_amount', 'total_units', 'principal_balance',
            'interest_balance', 'total_outstanding_balance', 'amount_disbursed',
            'principal_amount', 'interest_amount', 'fees_amount', 'penalty_amount',
            'unallocated_amount', 'account_number']);
        $errors = [];
        foreach ($fields as $field) {
            if (array_key_exists($field, $request->all())) {
                $errors[$field] = 'This field is generated by the workflow and cannot be submitted.';
            }
        }
        if ($errors) {
            throw \Illuminate\Validation\ValidationException::withMessages($errors);
        }
    }

    protected function requireSaccoPermission(string $permission): void
    {
        if (!auth()->check()) {
            abort(401);
        }

        if (!$this->hasSaccoPermission($permission)) {
            abort(403);
        }
    }

    protected function hasSaccoPermission(string $permission): bool
    {
        if (!auth()->check()) {
            return false;
        }
        $isAdministrator = auth()->user()->roles()->where(function ($query) {
            $query->whereIn('name', ['sacco_admin', 'super_admin', 'administrator'])
                ->orWhereIn('key_name', ['sacco_admin', 'super_admin', 'administrator']);
        })->exists();

        return $isAdministrator || auth()->user()->can($permission);
    }
}
